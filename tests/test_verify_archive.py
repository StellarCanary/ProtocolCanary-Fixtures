"""Tests for tools/pack/verify_archive.py (F-012, CF-06 sections 5 to 9).

The negative archives are generated by the tests, not downloaded.

Stdlib only: the CI `validate` job runs `unittest discover` on a bare
interpreter.

Run with: python3 -m unittest discover tests
"""
from __future__ import annotations

import contextlib
import io
import json
import os
import subprocess
import sys
import tarfile
import tempfile
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pack_support as support  # noqa: E402

pack = support.pack
verify = support.verify_archive

TEMP_PREFIX = "canary-pack-verify-"


def leftover_directories() -> set[str]:
    return {n for n in os.listdir(tempfile.gettempdir()) if n.startswith(TEMP_PREFIX)}


class VerifyBase(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.before = leftover_directories()

    def tearDown(self) -> None:
        # The verifier's own scratch directory is removed on every path.
        self.assertEqual(leftover_directories(), self.before)

    def valid_archive(self) -> Path:
        support.write_pack(self.root)
        return pack.build_archive(self.root / "pack", self.root / "out", "1.0.0").path

    def hostile(self, extra, name: str = "hostile.tar.gz") -> Path:
        entries = support.valid_members(self.root / "src") + extra
        return support.tar_gz(entries, self.root / name)

    def check_refused(self, archive: Path, pattern: str) -> None:
        result = verify.verify_archive(archive)
        self.assertFalse(result.ok)
        self.assertRegex("\n".join(result.problems), pattern)


class PositiveTests(VerifyBase):
    def test_a_built_archive_verifies(self) -> None:
        result = verify.verify_archive(self.valid_archive())
        self.assertEqual(result.problems, [])
        self.assertEqual((result.fixtures, result.files), (2, 3))

    def test_archive_hash_and_manifest_pins_are_accepted(self) -> None:
        manifest = support.manifest
        archive = self.valid_archive()
        document = manifest.build_manifest(
            archive, revision=support.REVISION, engines=["0.2.0"]
        )
        result = verify.verify_archive(
            archive,
            expected_sha256=document["archive"]["sha256"],
            expected_digest=document["packDigest"],
        )
        self.assertTrue(result.ok, result.problems)

    def test_the_real_protocol_28_pack_round_trips(self) -> None:
        info = pack.build_archive(support.REPO_ROOT / "protocol-28", self.root / "o", "9.9.9")
        result = verify.verify_archive(info.path, expected_sha256=info.sha256)
        self.assertTrue(result.ok, result.problems)

    def test_cli_exit_code_zero(self) -> None:
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = verify.main([str(self.valid_archive())])
        self.assertEqual(code, 0)
        self.assertIn("OK:", out.getvalue())


class ContentFailureTests(VerifyBase):
    def test_a_corrupted_fixture_is_reported(self) -> None:
        entries = []
        for info, data in support.valid_members(self.root / "src"):
            if info.name == "rpc/b.toml":
                data = data.replace(b'surface = "rpc"', b'surface = "ftp"')
                info = support.file_info(info.name, len(data))
            entries.append((info, data))
        archive = support.tar_gz(entries, self.root / "corrupt.tar.gz")
        result = verify.verify_archive(archive)
        self.assertFalse(result.ok)
        self.assertTrue(any("digest" in p or "surface" in p for p in result.problems), result.problems)

    def test_a_missing_file_is_reported(self) -> None:
        entries = [
            (i, d) for i, d in support.valid_members(self.root / "src") if i.name != "xdr/a.bin"
        ]
        archive = support.tar_gz(entries, self.root / "missing.tar.gz")
        result = verify.verify_archive(archive)
        self.assertFalse(result.ok)
        self.assertTrue(result.problems)

    def test_a_missing_registry_is_reported(self) -> None:
        entries = [
            (i, d) for i, d in support.valid_members(self.root / "src") if i.name != "registry.json"
        ]
        self.check_refused(support.tar_gz(entries, self.root / "noreg.tar.gz"), "registry.json")

    def test_a_registry_that_disagrees_with_the_fixtures_is_reported(self) -> None:
        entries = []
        for info, data in support.valid_members(self.root / "src"):
            if info.name == "registry.json":
                data = data.replace(b'"golden rpc"', b'"edited"')
                info = support.file_info(info.name, len(data))
            entries.append((info, data))
        archive = support.tar_gz(entries, self.root / "stale.tar.gz")
        self.check_refused(archive, "registry")

    def test_a_non_json_registry_is_reported(self) -> None:
        entries = [
            (i, d) for i, d in support.valid_members(self.root / "src") if i.name != "registry.json"
        ]
        entries.append(support.entry("registry.json", b"{not json"))
        self.check_refused(support.tar_gz(entries, self.root / "bad.tar.gz"), "not valid JSON")

    def test_wrong_archive_checksum(self) -> None:
        archive = self.valid_archive()
        result = verify.verify_archive(archive, expected_sha256="0" * 64)
        self.assertFalse(result.ok)
        self.assertIn("does not match", result.problems[0])

    def test_wrong_manifest_pack_digest(self) -> None:
        archive = self.valid_archive()
        result = verify.verify_archive(archive, expected_digest="sha256:" + "0" * 64)
        self.assertFalse(result.ok)
        self.assertIn("expected", "\n".join(result.problems))


class UnsafeArchiveTests(VerifyBase):
    """Each archive must be refused as a whole, with the reason named."""

    def test_path_traversal(self) -> None:
        self.check_refused(self.hostile([support.entry("../escape.toml", b"x")]), r"\.\.")

    def test_embedded_dot_dot(self) -> None:
        self.check_refused(self.hostile([support.entry("xdr/../../e.toml", b"x")]), r"\.\.")

    def test_absolute_path(self) -> None:
        self.check_refused(self.hostile([support.entry("/etc/passwd", b"x")]), "absolute")

    def test_backslash_in_a_name(self) -> None:
        self.check_refused(self.hostile([support.entry("a\\b.toml", b"x")]), "backslash")

    def archive_with(self, extra, index: int) -> Path:
        """A fresh golden pack plus ``extra`` entries, so loops do not collide."""
        entries = support.valid_members(self.root / f"src-{index}") + extra
        return support.tar_gz(entries, self.root / f"hostile-{index}.tar.gz")

    def test_windows_reserved_device_names(self) -> None:
        for index, name in enumerate(
            (
                "xdr/con.toml",
                "NUL",
                "xdr/Aux.toml",
                "xdr/com1.toml",
                "xdr/lpt9.toml",
                "xdr/aux.v2.toml",
                "con/f.toml",
            )
        ):
            with self.subTest(name=name):
                self.check_refused(
                    self.archive_with([support.entry(name, support.A_TOML)], index),
                    "device name",
                )

    def test_non_portable_segments_and_characters(self) -> None:
        for index, name in enumerate(
            (
                "xdr/bad./f.toml",
                "xdr/bad /f.toml",
                "xdr/a:b.toml",
                "xdr/a?.toml",
                "xdr/a*.toml",
                "xdr/a<b.toml",
                "xdr/a>b.toml",
                'xdr/a"b.toml',
                "xdr/a|b.toml",
            )
        ):
            with self.subTest(name=name):
                self.check_refused(
                    self.archive_with([support.entry(name, support.A_TOML)], index),
                    "dot or a space|Windows does not allow",
                )

    def test_portable_names_and_unicode_lookalikes_are_accepted(self) -> None:
        for name in (
            "xdr/console.toml",
            "xdr/p28-xdr-con.toml",
            "xdr/lpt10.toml",
            "xdr/\u0421ON.toml",  # Cyrillic ES, not an ASCII C
        ):
            with self.subTest(name=name):
                verify._check_member_path(name)

    def test_symbolic_link(self) -> None:
        extra = [support.link_entry("xdr/link.toml", "/etc/passwd", hard=False)]
        self.check_refused(self.hostile(extra), "symbolic link")

    def test_hard_link(self) -> None:
        extra = [support.link_entry("xdr/hard.toml", "xdr/a.toml", hard=True)]
        self.check_refused(self.hostile(extra), "hard link")

    def test_device_node(self) -> None:
        info = tarfile.TarInfo("xdr/dev")
        info.type = tarfile.CHRTYPE
        self.check_refused(self.hostile([(info, None)]), "special file")

    def test_duplicate_path(self) -> None:
        self.check_refused(
            self.hostile([support.entry("xdr/a.toml", support.A_TOML)]), "more than once"
        )

    def test_case_fold_duplicate(self) -> None:
        self.check_refused(
            self.hostile([support.entry("xdr/A.toml", support.A_TOML)]), "letter case"
        )

    def test_setuid_bit(self) -> None:
        self.check_refused(
            self.hostile([support.entry("xdr/x.toml", b"x", mode=0o4755)]), "setuid"
        )

    def test_sticky_bit(self) -> None:
        self.check_refused(
            self.hostile([support.entry("xdr/y.toml", b"x", mode=0o1644)]), "sticky"
        )

    def test_oversize_file(self) -> None:
        big = b"#" * (verify.MAX_FILE_BYTES + 1)
        self.check_refused(self.hostile([support.entry("big.toml", big)]), "limit")

    def test_total_size(self) -> None:
        chunk = b"#" * verify.MAX_FILE_BYTES
        extra = [
            support.entry(f"d/f{i}.toml", chunk)
            for i in range(verify.MAX_TOTAL_BYTES // verify.MAX_FILE_BYTES + 1)
        ]
        self.check_refused(self.hostile(extra), "uncompressed")

    def test_too_many_entries(self) -> None:
        extra = [support.entry(f"m/f{i:04d}.toml", b"") for i in range(verify.MAX_ENTRIES + 1)]
        self.check_refused(self.hostile(extra), "entries")

    def test_too_deep(self) -> None:
        name = "/".join(["d"] * verify.MAX_DEPTH) + "/f.toml"
        self.check_refused(self.hostile([support.entry(name, b"x")]), "deeper")

    def test_nothing_is_written_outside_the_destination(self) -> None:
        victim = self.root / "escape.toml"
        archive = self.hostile([support.entry("../escape.toml", b"x")])
        verify.verify_archive(archive)
        self.assertFalse(victim.exists())

    def test_truncated_gzip_is_unreadable(self) -> None:
        archive = self.valid_archive()
        data = archive.read_bytes()
        archive.write_bytes(data[: len(data) // 2])
        with self.assertRaises(verify.UnreadableArchive):
            verify.verify_archive(archive)

    def test_not_an_archive_is_unreadable(self) -> None:
        junk = self.root / "junk.tar.gz"
        junk.write_bytes(b"not a gzip stream at all")
        with self.assertRaises(verify.UnreadableArchive):
            verify.verify_archive(junk)

    def test_missing_archive(self) -> None:
        with self.assertRaisesRegex(verify.UnreadableArchive, "not found"):
            verify.verify_archive(self.root / "nope.tar.gz")

    def test_cli_exit_codes(self) -> None:
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            self.assertEqual(verify.main([str(self.root / "nope.tar.gz")]), 2)
            bad = self.hostile([support.entry("../x.toml", b"x")])
            self.assertEqual(verify.main([str(bad)]), 1)
        self.assertIn("FAILED", err.getvalue())

    def test_manifest_and_explicit_pin_must_agree(self) -> None:
        manifest = support.manifest
        archive = self.valid_archive()
        document = manifest.build_manifest(archive, revision=support.REVISION, engines=[])
        path = self.root / "m.json"

        path.write_text(json.dumps(document), encoding="utf-8")
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            code = verify.main([str(archive), "--manifest", str(path), "--sha256", "f" * 64])
        self.assertEqual(code, 1)
        self.assertIn("disagrees", err.getvalue())
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(verify.main([str(archive), "--manifest", str(path)]), 0)


